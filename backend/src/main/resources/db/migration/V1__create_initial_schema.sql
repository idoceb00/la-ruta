-- V1: initial schema, generated from the JPA entities and cleaned up by hand.
-- Tables are ordered by dependency so foreign keys can be declared inline.

create table users (
                       id            bigint generated by default as identity,
                       username      varchar(255) not null,
                       password_hash varchar(255) not null,
                       created_at    timestamp(6) with time zone not null,
                       updated_at    timestamp(6) with time zone not null,
                       created_by    bigint,
                       modified_by   bigint,
                       constraint pk_users primary key (id),
                       constraint uk_users_username unique (username)
);

create table communities (
                             id          bigint generated by default as identity,
                             name        varchar(255) not null,
                             invite_code varchar(255) not null,
                             created_at  timestamp(6) with time zone not null,
                             updated_at  timestamp(6) with time zone not null,
                             created_by  bigint,
                             modified_by bigint,
                             constraint pk_communities primary key (id),
                             constraint uk_communities_invite_code unique (invite_code)
);

create table memberships (
                             id           bigint generated by default as identity,
                             community_id bigint not null,
                             user_id      bigint not null,
                             role         varchar(255) not null,
                             created_at   timestamp(6) with time zone not null,
                             updated_at   timestamp(6) with time zone not null,
                             created_by   bigint,
                             modified_by  bigint,
                             constraint pk_memberships primary key (id),
                             constraint uk_memberships_community_user unique (community_id, user_id),
                             constraint ck_memberships_role check (role in ('ADMIN', 'MEMBER')),
                             constraint fk_memberships_community foreign key (community_id) references communities (id) on delete cascade,
                             constraint fk_memberships_user foreign key (user_id) references users (id) on delete cascade
);

create table tapas (
                       id          bigint generated by default as identity,
                       name        varchar(100) not null,
                       created_at  timestamp(6) with time zone not null,
                       updated_at  timestamp(6) with time zone not null,
                       created_by  bigint,
                       modified_by bigint,
                       constraint pk_tapas primary key (id),
                       constraint uk_tapas_name unique (name)
);

create table bars (
                      id           bigint generated by default as identity,
                      community_id bigint not null,
                      name         varchar(255) not null,
                      address      varchar(255),
                      city         varchar(255),
                      zone         varchar(255),
                      rating_sum   bigint not null,
                      rating_count bigint not null,
                      version      bigint not null,
                      created_at   timestamp(6) with time zone not null,
                      updated_at   timestamp(6) with time zone not null,
                      created_by   bigint,
                      modified_by  bigint,
                      constraint pk_bars primary key (id),
                      constraint fk_bars_community foreign key (community_id) references communities (id) on delete cascade
);

create table bar_tapas (
                           id           bigint generated by default as identity,
                           bar_id       bigint not null,
                           tapa_id      bigint not null,
                           rating_sum   bigint not null,
                           rating_count bigint not null,
                           version      bigint not null,
                           created_at   timestamp(6) with time zone not null,
                           updated_at   timestamp(6) with time zone not null,
                           created_by   bigint,
                           modified_by  bigint,
                           constraint pk_bar_tapas primary key (id),
                           constraint uk_bar_tapas_bar_tapa unique (bar_id, tapa_id),
                           constraint fk_bar_tapas_bar foreign key (bar_id) references bars (id) on delete cascade,
                           constraint fk_bar_tapas_tapa foreign key (tapa_id) references tapas (id) on delete cascade
);

create table bar_reviews (
                             id          bigint generated by default as identity,
                             bar_id      bigint not null,
                             user_id     bigint not null,
                             rating      integer,
                             notes       varchar(1000),
                             created_at  timestamp(6) with time zone not null,
                             updated_at  timestamp(6) with time zone not null,
                             created_by  bigint,
                             modified_by bigint,
                             constraint pk_bar_reviews primary key (id),
                             constraint uk_bar_reviews_bar_user unique (bar_id, user_id),
                             constraint fk_bar_reviews_bar foreign key (bar_id) references bars (id) on delete cascade,
                             constraint fk_bar_reviews_user foreign key (user_id) references users (id) on delete cascade
);

create table tapa_reviews (
                              id          bigint generated by default as identity,
                              bar_tapa_id bigint not null,
                              user_id     bigint not null,
                              rating      integer,
                              fav         boolean not null,
                              notes       varchar(1000),
                              created_at  timestamp(6) with time zone not null,
                              updated_at  timestamp(6) with time zone not null,
                              created_by  bigint,
                              modified_by bigint,
                              constraint pk_tapa_reviews primary key (id),
                              constraint uk_tapa_reviews_bar_tapa_user unique (bar_tapa_id, user_id),
                              constraint fk_tapa_reviews_bar_tapa foreign key (bar_tapa_id) references bar_tapas (id) on delete cascade,
                              constraint fk_tapa_reviews_user foreign key (user_id) references users (id) on delete cascade
);

-- Indexes on foreign keys not already covered as the leading column of a unique constraint
create index idx_bars_community_id on bars (community_id);
